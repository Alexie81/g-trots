// Run against the loopback preview only; exercises real renderer + PHP service.
const {app,BrowserWindow}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
const output=path.resolve(__dirname,'../reports/fixed-assets-local');
app.setPath('userData',path.join(output,'test-profile'));
app.whenReady().then(async()=>{
  const win=new BrowserWindow({show:false,width:1700,height:1100,webPreferences:{offscreen:true,backgroundThrottling:false,nodeIntegration:false,contextIsolation:true}});
  const errors=[];
  const fixtureName='TEST UI · calculator diagnoză '+Date.now();
  win.webContents.on('console-message',(_e,level,message)=>{if(level===3 && !message.includes('404')) errors.push(message);});
  const run=code=>win.webContents.executeJavaScript(code);
  const wait=async code=>{for(let n=0;n<120;n++){if(await run(code))return;await new Promise(r=>setTimeout(r,100));}throw new Error('Timeout: '+code);};
  const click=selector=>run(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const fill=(selector,value)=>run(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const check=async(code,message)=>{if(!await run(code))throw new Error(message);};
  await win.loadURL('http://127.0.0.1:4175/');
  await wait(`Boolean(document.getElementById('shop-fixed-assets-search'))`);
  await click('[data-commerce-add="shop-fixed-assets-content"]');
  await wait(`getComputedStyle(document.getElementById('shop-fixed-asset-create-modal')).opacity==='1'`);
  await fill('#shop-fixed-asset-number','QA-UI-'+Date.now());
  await fill('[data-fixed-asset-line-field="product_name"]',fixtureName);
  await fill('[data-fixed-asset-line-field="quantity"]','2');
  await fill('[data-fixed-asset-line-field="unit_price"]','100');
  await check(`document.querySelector('[data-fixed-asset-line-field="vat_value"]').value==='42.00'`,'VAT auto on create');
  await fill('[data-fixed-asset-line-field="vat_value"]','39.95');
  await click('#shop-fixed-asset-add-line');
  await check(`(()=>{const e=document.querySelector('[data-fixed-asset-line-remove="1"]');const b=e.getBoundingClientRect(),h=e.parentElement.getBoundingClientRect();return b.top>=h.top && b.bottom<=h.bottom && Math.abs((b.top+b.bottom-h.top-h.bottom)/2)<1;})()`,'Remove X is centered within its header');
  await click('[data-fixed-asset-line-remove="1"]');
  await run(`(()=>{const dt=new DataTransfer();dt.items.add(new File(['<document>Demo</document>'],'factura-demo.xml',{type:'application/xml'}));dt.items.add(new File(['<garantie>Demo</garantie>'],'garantie-demo.xml',{type:'application/xml'}));const el=document.getElementById('shop-fixed-asset-file-input');el.files=dt.files;el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await check(`document.querySelectorAll('[data-fixed-asset-pending-remove]').length===2`,'Multiple create attachments');
  await run(`document.getElementById('shop-fixed-asset-create-form').requestSubmit()`);
  await wait(`document.getElementById('shop-fixed-asset-create-modal').hidden`);
  await fill('#shop-fixed-assets-search',fixtureName);
  await wait(`document.querySelectorAll('[data-fixed-asset-row]').length===1 && document.querySelector('[data-fixed-asset-row]').innerText.includes('TEST UI')`);
  const id=await run(`document.querySelector('[data-fixed-asset-row]').dataset.fixedAssetRow`);
  await click(`[data-fixed-asset-edit="${id}"]`);
  await wait(`document.getElementById('shop-fixed-asset-editor-title').textContent.startsWith('Editează')`);
  await check(`document.querySelector('[data-fixed-asset-line-field="vat_value"]').value==='39.95'`,'Manual VAT preserved when opening editor');
  await fill('[data-fixed-asset-line-field="unit_price"]','120');
  await check(`document.querySelector('[data-fixed-asset-line-field="vat_value"]').value==='39.95'`,'Manual VAT preserved when price changes');
  await click('[data-fixed-asset-vat-auto="0"]');
  await check(`document.querySelector('[data-fixed-asset-line-field="vat_value"]').value==='50.40'`,'Reset automatic VAT on edit');
  await fill('[data-fixed-asset-line-field="vat_value"]','49.99');
  await wait(`getComputedStyle(document.getElementById('shop-fixed-asset-create-modal')).opacity==='1'`);
  await new Promise(resolve=>setTimeout(resolve,250));
  fs.writeFileSync(path.join(output,'editare-tva-fisiere.png'),(await win.webContents.capturePage()).toPNG());
  await run(`document.getElementById('shop-fixed-asset-create-form').requestSubmit()`);
  await wait(`document.getElementById('shop-fixed-asset-create-modal').hidden`);
  await click(`[data-fixed-asset-open="${id}"]`);
  await wait(`document.querySelectorAll('[data-fixed-asset-file-download]').length===2`);
  await click('[data-fixed-asset-detail-dispose]');
  await wait(`!document.getElementById('shop-fixed-asset-disposal-modal').hidden`);
  await fill('#shop-fixed-asset-disposal-quantity','-1');await fill('#shop-fixed-asset-disposal-reason','Defect test UI');
  await run(`document.getElementById('shop-fixed-asset-disposal-form').requestSubmit()`);
  await wait(`document.querySelectorAll('[data-fixed-asset-disposal-edit]').length===1`);
  await click('[data-fixed-asset-disposal-edit]');
  await wait(`document.getElementById('shop-fixed-asset-disposal-save').textContent==='Salvează modificările'`);
  await fill('#shop-fixed-asset-disposal-quantity','-0.5');
  await run(`document.getElementById('shop-fixed-asset-disposal-form').requestSubmit()`);
  await wait(`document.getElementById('shop-fixed-asset-disposal-modal').hidden`);
  await check(`document.querySelector('.shop-fixed-asset-detail-hero > b').textContent.startsWith('1,5')`,'Disposal edit recalculates availability');
  await click('[data-fixed-asset-disposal-delete]');await click('#shop-fixed-asset-confirm-submit');
  await wait(`document.getElementById('shop-fixed-asset-confirm-modal').hidden`);
  await check(`document.querySelector('.shop-fixed-asset-detail-hero > b').textContent.startsWith('2')`,'Disposal delete restores availability');
  await run(`(()=>{const dt=new DataTransfer();dt.items.add(new File(['<pv>Demo</pv>'],'proces-verbal.xml',{type:'application/xml'}));const el=document.getElementById('shop-fixed-asset-files-input');el.files=dt.files;el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await wait(`document.querySelectorAll('[data-fixed-asset-file-download]').length===3`);
  await click('[data-fixed-asset-file-delete]');await click('#shop-fixed-asset-confirm-submit');
  await wait(`document.getElementById('shop-fixed-asset-confirm-modal').hidden`);
  await check(`document.querySelectorAll('[data-fixed-asset-file-download]').length===2`,'Individual file delete');
  await click('#shop-fixed-asset-edit');
  await wait(`!document.getElementById('shop-fixed-asset-create-modal').hidden`);
  await check(`document.querySelector('[data-fixed-asset-line-field="vat_value"]').value==='49.99'`,'Edited manual VAT persists through other operations');
  await click('#shop-fixed-asset-delete-document');await click('#shop-fixed-asset-confirm-submit');
  await wait(`document.getElementById('shop-fixed-asset-confirm-modal').hidden`);
  await wait(`document.querySelectorAll('[data-fixed-asset-row]').length===0`);
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('UI PASS: add/edit manual and automatic VAT, multiple files, disposal edit/delete, document cascade, centered remove button.');
  win.destroy();app.quit();
}).catch(error=>{console.error(error);app.exit(1);});
